interface PageMetaInput {
  /** Route path, e.g. '/services' */
  path: string;
  /** <title> (the layout template appends "| Axonix Tech") */
  title: string;
  description: string;
  ogTitle?: string;
  ogDescription?: string;
}

/**
 * Builds page metadata that always includes a canonical URL and the share image.
 * Next.js replaces (not merges) the `openGraph` object when a page defines its own,
 * so pages that set openGraph must re-declare the image — this helper does that.
 */
export function pageMetadata({ path, title, description, ogTitle, ogDescription }: PageMetaInput): Metadata {
  const socialTitle = ogTitle ?? `${title} | Axonix Tech`;
  const socialDescription = ogDescription ?? description;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: 'website',
      locale: 'en_US',
      siteName: 'Axonix Tech',
      url: path,
      title: socialTitle,
      description: socialDescription,
      images: [OG_IMAGE],
    },
    twitter: {
      card: 'summary_large_image',
      title: socialTitle,
      description: socialDescription,
      images: [OG_IMAGE.url],
    },
  };
}

